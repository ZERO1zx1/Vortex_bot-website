from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

from core.database import DatabaseTimestamp, _postgres_params, _postgres_sql
from utils.time_utils import from_db

ROOT = Path(__file__).resolve().parents[1]


def test_qmark_parameters_are_numbered_for_asyncpg() -> None:
    sql = _postgres_sql(
        "SELECT '?' AS literal FROM users WHERE user_id = ? AND level >= ?"
    )
    assert sql == "SELECT '?' AS literal FROM users WHERE user_id = $1 AND level >= $2"


def test_iso_timestamp_parameters_are_bound_as_datetimes() -> None:
    params = _postgres_params(
        (DatabaseTimestamp("2026-11-24 08:30:00"), "2026-11-24 08:30:00")
    )
    assert params == (
        datetime(2026, 11, 24, 8, 30, tzinfo=UTC),
        "2026-11-24 08:30:00",
    )


def test_baseline_schema_uses_postgresql_types_and_immutable_ledgers() -> None:
    schema = (ROOT / "migrations" / "001_baseline.sql").read_text(encoding="utf-8")
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY" in schema
    assert "TIMESTAMPTZ" in schema
    assert "JSONB" in schema
    assert "prevent_audit_mutation" in schema
    assert schema.count("BEFORE TRUNCATE") == 3
    assert "PRAGMA" not in schema
    assert "AUTOINCREMENT" not in schema
    assert "datetime('now')" not in schema


def test_production_repositories_do_not_import_sqlite() -> None:
    source = "\n".join(
        path.read_text(encoding="utf-8")
        for path in sorted((ROOT / "repositories").glob("*.py"))
    )
    assert "aiosqlite" not in source
    assert "INSERT OR IGNORE" not in source
    assert "datetime('now')" not in source
    assert "inventory.quantity + excluded.quantity" in source
    lottery = (ROOT / "repositories" / "lottery_repo.py").read_text(encoding="utf-8")
    assert "RETURNING ticket_id" in lottery


def test_docker_context_excludes_nested_secrets_and_test_files() -> None:
    dockerignore = (ROOT.parent / ".dockerignore").read_text(encoding="utf-8")
    assert "**/.env" in dockerignore
    assert "**/.venv" in dockerignore
    assert "**/tests" in dockerignore


def test_postgresql_datetime_rows_are_accepted() -> None:
    moment = datetime(2026, 11, 24, 8, 30, tzinfo=UTC)
    assert from_db(moment) == moment
